def tr(language: str, key: str, **kwargs) -> str:
    """Return a localized, formatted UI message with Korean fallback."""
    language = language if language in STRINGS else "ko"
    template = STRINGS[language].get(key, STRINGS["ko"].get(key, key))
    return template.format(**kwargs)


def supported_languages() -> tuple[str, ...]:
    return tuple(STRINGS.keys())